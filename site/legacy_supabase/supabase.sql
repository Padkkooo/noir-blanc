create table if not exists public.cart_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_key text not null,
  name text not null,
  image text not null,
  product_type text,
  price numeric(12,2) not null,
  quantity integer not null default 1 check (quantity > 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, product_key)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  order_number text not null unique,
  customer_name text not null,
  phone text not null,
  email text not null,
  delivery text not null,
  address text not null,
  payment text not null,
  comment text,
  total numeric(12,2) not null,
  status text not null default 'Новый',
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_key text not null,
  name text not null,
  image text not null,
  price numeric(12,2) not null,
  quantity integer not null check (quantity > 0)
);

alter table public.cart_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

revoke all on table public.cart_items, public.orders, public.order_items from anon;
grant select, insert, update, delete on table public.cart_items to authenticated;
grant select, insert on table public.orders to authenticated;
grant select, insert on table public.order_items to authenticated;

drop policy if exists "cart own select" on public.cart_items;
drop policy if exists "cart own insert" on public.cart_items;
drop policy if exists "cart own update" on public.cart_items;
drop policy if exists "cart own delete" on public.cart_items;
create policy "cart own select" on public.cart_items for select to authenticated using ((select auth.uid()) = user_id);
create policy "cart own insert" on public.cart_items for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "cart own update" on public.cart_items for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "cart own delete" on public.cart_items for delete to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "orders own select" on public.orders;
drop policy if exists "orders own insert" on public.orders;
create policy "orders own select" on public.orders for select to authenticated using ((select auth.uid()) = user_id);
create policy "orders own insert" on public.orders for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "order items own select" on public.order_items;
drop policy if exists "order items own insert" on public.order_items;
create policy "order items own select" on public.order_items for select to authenticated using ((select auth.uid()) = user_id);
create policy "order items own insert" on public.order_items for insert to authenticated with check ((select auth.uid()) = user_id);

create index if not exists cart_items_user_id_idx on public.cart_items(user_id);
create index if not exists orders_user_id_idx on public.orders(user_id);
create index if not exists order_items_user_id_idx on public.order_items(user_id);

